package brandart

import (
	"fmt"
	"math"
	"strings"
)

// The apps draw the marks in their own interface (sign-in screens, the server's card) from code
// rather than pictures, so they stay sharp at every size. These write that code from the same
// drawings: Kotlin ImageVectors for Compose and SwiftUI Canvas drawing for the Apple apps.

const generatedNote = "Generated by WittyMediaServer's scripts/genicon from the brand drawings (docs/BRAND.md). Do not edit:\n// run scripts/sync-brand.sh instead."

func (c Colour) kotlin() string { return fmt.Sprintf("Color(0x%02X%02X%02X%02X)", c.A, c.R, c.G, c.B) }

func f32(v float64) string { return num(v) + "f" }

func (p Paint) kotlinBrush() string {
	if len(p.Stops) == 0 {
		return "SolidColor(" + p.Solid.kotlin() + ")"
	}
	var stops []string
	for _, s := range p.Stops {
		stops = append(stops, fmt.Sprintf("%s to %s", f32(s.At), s.C.kotlin()))
	}
	if p.Radial {
		r := math.Hypot(p.To.X-p.From.X, p.To.Y-p.From.Y)
		return fmt.Sprintf("Brush.radialGradient(%s, center = Offset(%s, %s), radius = %s)", strings.Join(stops, ", "), f32(p.From.X), f32(p.From.Y), f32(r))
	}
	return fmt.Sprintf("Brush.linearGradient(%s, start = Offset(%s, %s), end = Offset(%s, %s))", strings.Join(stops, ", "), f32(p.From.X), f32(p.From.Y), f32(p.To.X), f32(p.To.Y))
}

// KotlinFile is a Kotlin source file holding each named drawing as an ImageVector of dp×dp.
func KotlinFile(pkg string, names []string, arts []Art, dp float64) []byte {
	var b strings.Builder
	b.WriteString("// SPDX-License-Identifier: GPL-3.0-or-later\n// Copyright (C) 2026 WittyWilla and contributors\n// " + generatedNote + "\n")
	b.WriteString("package " + pkg + "\n\n")
	for _, imp := range []string{"androidx.compose.ui.geometry.Offset", "androidx.compose.ui.graphics.Brush", "androidx.compose.ui.graphics.Color", "androidx.compose.ui.graphics.SolidColor", "androidx.compose.ui.graphics.vector.ImageVector", "androidx.compose.ui.graphics.vector.addPathNodes", "androidx.compose.ui.unit.dp"} {
		b.WriteString("import " + imp + "\n")
	}
	b.WriteString("\n/** The family's marks, drawn from the same paths as every icon. */\nobject BrandArt {\n")
	for i, a := range arts {
		fmt.Fprintf(&b, "    val %s: ImageVector by lazy {\n        ImageVector.Builder(\"%s\", %s.dp, %s.dp, %s, %s)\n", names[i], names[i], num(dp), num(dp*a.H/a.W), f32(a.W), f32(a.H))
		for _, l := range a.Layers {
			fmt.Fprintf(&b, "            .addPath(addPathNodes(\"%s\"), fill = %s)\n", l.Path.d(), l.Paint.kotlinBrush())
		}
		b.WriteString("            .build()\n    }\n")
	}
	b.WriteString("}\n")
	return []byte(b.String())
}

func (c Colour) swift() string {
	return fmt.Sprintf("Color(.sRGB, red: %s, green: %s, blue: %s, opacity: %s)", num(float64(c.R)/255), num(float64(c.G)/255), num(float64(c.B)/255), num(float64(c.A)/255))
}

func (p Path) swift() string {
	var b strings.Builder
	b.WriteString("Path { p in ")
	pt := func(q Pt) string { return fmt.Sprintf("CGPoint(x: %s, y: %s)", num(q.X), num(q.Y)) }
	for _, s := range p.subs {
		fmt.Fprintf(&b, "p.move(to: %s); ", pt(s.Start))
		for _, e := range s.Elems {
			if e.Curve {
				fmt.Fprintf(&b, "p.addCurve(to: %s, control1: %s, control2: %s); ", pt(e.To), pt(e.C1), pt(e.C2))
			} else {
				fmt.Fprintf(&b, "p.addLine(to: %s); ", pt(e.To))
			}
		}
		b.WriteString("p.closeSubpath(); ")
	}
	b.WriteString("}")
	return b.String()
}

func (p Paint) swift() string {
	if len(p.Stops) == 0 {
		return ".color(" + p.Solid.swift() + ")"
	}
	var stops []string
	for _, s := range p.Stops {
		stops = append(stops, fmt.Sprintf(".init(color: %s, location: %s)", s.C.swift(), num(s.At)))
	}
	g := "Gradient(stops: [" + strings.Join(stops, ", ") + "])"
	if p.Radial {
		r := math.Hypot(p.To.X-p.From.X, p.To.Y-p.From.Y)
		return fmt.Sprintf(".radialGradient(%s, center: CGPoint(x: %s, y: %s), startRadius: 0, endRadius: %s)", g, num(p.From.X), num(p.From.Y), num(r))
	}
	return fmt.Sprintf(".linearGradient(%s, startPoint: CGPoint(x: %s, y: %s), endPoint: CGPoint(x: %s, y: %s))", g, num(p.From.X), num(p.From.Y), num(p.To.X), num(p.To.Y))
}

// SwiftFile is a Swift source file with a function per drawing that paints it into a
// GraphicsContext scaled to the canvas.
func SwiftFile(names []string, arts []Art) []byte {
	var b strings.Builder
	b.WriteString("// SPDX-License-Identifier: GPL-3.0-or-later\n// Copyright (C) 2026 WittyWilla and contributors\n// " + generatedNote + "\nimport SwiftUI\n\n")
	b.WriteString("/// The family's marks, drawn from the same paths as every icon.\nenum BrandArt {\n")
	for i, a := range arts {
		fmt.Fprintf(&b, "    static func %s(_ context: inout GraphicsContext, _ size: CGSize) {\n", names[i])
		fmt.Fprintf(&b, "        context.scaleBy(x: size.width / %s, y: size.height / %s)\n", num(a.W), num(a.H))
		for _, l := range a.Layers {
			fmt.Fprintf(&b, "        context.fill(%s, with: %s)\n", l.Path.swift(), l.Paint.swift())
		}
		b.WriteString("    }\n")
	}
	b.WriteString("}\n")
	return []byte(b.String())
}
