// The brand kit: every form of every logo, rendered, for anyone who needs one (a press page, a
// sticker, a slide, a store listing, a partner's site). Written by `genicon -target kit` into
// docs/brand/<concept>/, with a generated README showing them all.

// KitPNGSizes are the square sizes every mark and tile is rendered at.
var KitPNGSizes = []int{16, 24, 32, 48, 64, 128, 256, 512, 1024}

// KitLockupHeights are the heights the name-beside-mark lockups are rendered at.
var KitLockupHeights = []int{64, 128, 256, 512}

// kitVariant is one form of a product's logo.
type kitVariant struct {
	name, what string
	square     bool                               // a square mark (sizes from KitPNGSizes) or a lockup
	art        func(k Kit, p Product, px int) Art // the drawing at a size (px is the square's side or lockup's height)
	jpegOn     func(k Kit) []struct {
		name string
		c    Colour
	}
}

// markScale fits the glyph to 0.92 of its square: the kit's marks have no tile to sit in.
const markScale = 0.92 / 0.65

func (k Kit) lockupArt(p Product, h int, text, accent Colour, mono *Colour) Art {
	H := float64(h)
	m := k.Mark(p, h)
	layers := glyphAt(m.Glyph(), markScale)
	if mono != nil {
		layers = glyphAt([]Layer{{m.MonoPath(), Fill(*mono)}}, markScale)
		text, accent = *mono, *mono
	}
	mark := Art{W: Page, H: Page, Layers: layers}.Placed(0, 0, Pt{H / 2, H / 2}, H/Page)
	size := H * 0.5
	words, w := TextArt(k.Wordmark(p, text, accent), H*1.18, H/2+size*0.36, size, true)
	return Art{W: H*1.18 + w + H*0.06, H: H, Layers: append(mark.Layers, words...)}
}

func kitVariants(pal Palette) []kitVariant {
	black, white := Hex("#000000"), Hex("#ffffff")
	onBoth := func(k Kit) []struct {
		name string
		c    Colour
	} {
		return []struct {
			name string
			c    Colour
		}{{"on-dark", k.Pal.Night}, {"on-light", k.Pal.Paper}}
	}
	onLight := func(k Kit) []struct {
		name string
		c    Colour
	} {
		return []struct {
			name string
			c    Colour
		}{{"on-light", k.Pal.Paper}, {"on-white", white}}
	}
	onDark := func(k Kit) []struct {
		name string
		c    Colour
	} {
		return []struct {
			name string
			c    Colour
		}{{"on-dark", k.Pal.Night}, {"on-black", black}}
	}
	return []kitVariant{
		{"icon", "The app icon: the mark on its dark tile. Use it wherever the app itself is meant (a download button, a list of apps).", true,
			func(k Kit, p Product, px int) Art { return k.Tile(p, px) }, onBoth},
		{"mark-colour", "The mark alone in its colours, on transparency. Reads on dark and light backgrounds.", true,
			func(k Kit, p Product, px int) Art { return k.Glyph(p, px, markScale) }, onBoth},
		{"mark-black", "The mark in black on transparency (cuts are holes): for light backgrounds, print, engraving, one-colour use.", true,
			func(k Kit, p Product, px int) Art { return k.Mono(p, px, black, markScale) }, onLight},
		{"mark-white", "The mark in white on transparency (cuts are holes): for dark backgrounds and photographs.", true,
			func(k Kit, p Product, px int) Art { return k.Mono(p, px, white, markScale) }, onDark},
		{"lockup-dark", "The mark and the name, for dark backgrounds: light text with \"Media\" (or \"Reader\") in the accent, as on the website.", false,
			func(k Kit, p Product, px int) Art { return k.lockupArt(p, px, k.Pal.Text, k.Pal.AccentLite, nil) }, onDark},
		{"lockup-light", "The mark and the name, for light backgrounds: dark text with the accent part in violet.", false,
			func(k Kit, p Product, px int) Art { return k.lockupArt(p, px, k.Pal.Night, k.Pal.Accent, nil) }, onLight},
		{"lockup-black", "The mark and the name in black on transparency.", false,
			func(k Kit, p Product, px int) Art { c := black; return k.lockupArt(p, px, c, c, &c) }, onLight},
		{"lockup-white", "The mark and the name in white on transparency.", false,
			func(k Kit, p Product, px int) Art { c := white; return k.lockupArt(p, px, c, c, &c) }, onDark},
	}
}

// BuildKit renders every variant of every product's logo in every format, the module icons, and
// the README that shows them.
func (k Kit) BuildKit(modules map[string]string) Files {
	f := Files{}
	dir := "docs/brand/" + string(k.Concept) + "/"
	var readme strings.Builder
	fmt.Fprintf(&readme, "# The %s logos, every form\n\n", k.Concept)
	readme.WriteString("Generated by `go run ./scripts/genicon -target kit` (see [../../BRAND.md](../../BRAND.md)). Do not edit: change the drawings in `internal/brandart` and run it again.\n\n")
	readme.WriteString("Every variant comes as **SVG** (vector, any size), **PNG** (transparent where it says so) and **JPEG** (no transparency, so on a stated background). Square marks are rendered at " + sizesText(KitPNGSizes) + " pixels; the 16 to 32 pixel ones are drawn with heavier lines and fewer details, not shrunk. Lockups are rendered " + sizesText(KitLockupHeights) + " pixels high.\n\n")
	for _, p := range Products {
		fmt.Fprintf(&readme, "## %s\n\n", p.Name())
		for _, v := range kitVariants(k.Pal) {
			base := fmt.Sprintf("%s%s/%s/%s-%s", dir, p, v.name, p, v.name)
			rel := fmt.Sprintf("%s/%s/%s-%s", p, v.name, p, v.name)
			preview := 256
			sizes := KitPNGSizes
			if !v.square {
				preview = 128
				sizes = KitLockupHeights
			}
			ref := v.art(k, p, 0)
			if !v.square {
				ref = v.art(k, p, 256)
			}
			f[base+".svg"] = ref.SVG()
			var pngs []string
			for _, s := range sizes {
				a := v.art(k, p, s)
				w, h := s, s
				if !v.square {
					w = int(float64(s) * a.W / a.H)
				}
				name := fmt.Sprintf("%s-%d.png", base, s)
				f[name] = a.PNG(w, h)
				pngs = append(pngs, fmt.Sprintf("[%d](%s-%d.png)", s, rel, s))
			}
			var jpegs []string
			for _, bg := range v.jpegOn(k) {
				s := 1024
				if !v.square {
					s = 512
				}
				a := v.art(k, p, s)
				w, h := s, s
				if !v.square {
					w = int(float64(s) * a.W / a.H)
				}
				pad := s / 8
				img := image.NewRGBA(image.Rect(0, 0, w+2*pad, h+2*pad))
				Draw(img, a.Image(w, h), pad, pad)
				name := fmt.Sprintf("%s-%s-%d.jpg", base, bg.name, s)
				f[name] = jpegOn(img, bg.c)
				jpegs = append(jpegs, fmt.Sprintf("[%s](%s-%s-%d.jpg)", bg.name, rel, bg.name, s))
			}
			fmt.Fprintf(&readme, "**%s**: %s\n\n", v.name, v.what)
			fmt.Fprintf(&readme, "<img src=\"%s-%d.png\" height=\"%d\" alt=\"%s %s\">\n\n", rel, preview, preview/2, p.Name(), v.name)
			fmt.Fprintf(&readme, "SVG: [%s.svg](%s.svg) · PNG: %s · JPEG: %s\n\n", rel[strings.LastIndex(rel, "/")+1:], rel, strings.Join(pngs, " "), strings.Join(jpegs, " "))
		}
	}
	if len(modules) > 0 {
		readme.WriteString("## Modules\n\nEach module's icon (the catalogue shows them at 128). PNG only: the marks are drawn as distance fields.\n\n| Module | 128 | 512 |\n|---|---|---|\n")
		var ids []string
		for id := range modules {
			ids = append(ids, id)
		}
		sort.Strings(ids)
		for _, id := range ids {
			for _, s := range []int{128, 512} {
				if img := k.ModuleIcon(id, modules[id], s); img != nil {
					f[fmt.Sprintf("%smodules/%s-%d.png", dir, id, s)] = encodePNG(img)
				}
			}
			fmt.Fprintf(&readme, "| %s | <img src=\"modules/%s-128.png\" width=\"64\" alt=\"\"> | [512](modules/%s-512.png) |\n", id, id, id)
		}
		readme.WriteString("\n")
	}
	f[dir+"README.md"] = []byte(readme.String())
	return f
}

func jpegOn(img *image.RGBA, bg Colour) []byte {
	return JPEG(Opaque(img, bg))
}

func sizesText(s []int) string {
	var out []string
	for _, v := range s {
		out = append(out, fmt.Sprint(v))
	}
	return strings.Join(out[:len(out)-1], ", ") + " and " + out[len(out)-1]
}
