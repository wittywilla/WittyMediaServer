#!/usr/bin/env python3
"""Writes the design tokens as plain data, for clients that can't read CSS (the
Apple TV and Android TV apps). The CSS stays the single source; never edit the
results by hand:

  themes/tokens.json          type scale, spacing, shape, depth, motion, sizes, ten-foot rules
  themes/*/theme.json         "colors": every colour of that theme, resolved to #rrggbb or #rrggbbaa

Run from the repository root, after changing web/src/styles.css or a theme.css
(and after scripts/theme-contrast.py --fix):

  python scripts/design-tokens.py          write
  python scripts/design-tokens.py --check  fail if anything is out of date (CI)

Sizes are CSS pixels at normal scale (use them as dp or pt), times are
milliseconds, tracking is in em, radii are multiples of the theme's radius.
"""
import json, pathlib, re, sys

CHECK = '--check' in sys.argv
STYLES = pathlib.Path('web/src/styles.css')
HEADER = 'Generated by scripts/design-tokens.py from web/src/styles.css. Do not edit; see docs/DESIGN.md.'


def block(css, selector):
    """The declarations of the first rule with exactly this selector, as a dict."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    m = re.search(r'(?m)^' + re.escape(selector) + r'\s*\{(.*?)^\}', css, flags=re.S)
    if not m:
        raise SystemExit(f'no {selector} rule found')
    return {k: v.strip() for k, v in re.findall(r'--([\w-]+):\s*([^;]+);', m.group(1))}


def px(value):
    """A length in CSS pixels: 2.5rem, 16px, 650."""
    m = re.fullmatch(r'(-?[\d.]+)(rem|px|em)?', value.strip())
    if not m:
        raise SystemExit(f'not a length: {value}')
    n = float(m.group(1)) * (16 if m.group(2) == 'rem' else 1)
    return int(n) if n == int(n) else round(n, 3)


def clamp(value):
    """clamp(min, fluid, max) as {"min", "max"}."""
    m = re.fullmatch(r'clamp\(\s*([^,]+),.*,\s*([^,)]+)\)', value)
    if not m:
        raise SystemExit(f'not a clamp: {value}')
    return {'min': px(m.group(1)), 'max': px(m.group(2))}


def ms(value):
    return int(value.removesuffix('ms'))


def bezier(value):
    return [float(x) for x in re.findall(r'[\d.]+', value)]


def shadow(value):
    """box-shadow layers as {y, blur, opacity} (all black)."""
    return [{'y': px(y), 'blur': px(b), 'opacity': float(a)}
            for y, b, a in re.findall(r'0 ([\d.]+px) ([\d.]+px) (?:rgba?\(0,?\s*0,?\s*0\s*[,/]\s*([\d.]+)\))', value)]


def media(css, query):
    """Token overrides inside @media (query) { :root { ... } }."""
    m = re.search(r'@media ' + re.escape(query) + r'\s*\{\s*:root\s*\{([^}]*)\}', css)
    if not m:
        raise SystemExit(f'no @media {query} tokens found')
    return {k: v.strip() for k, v in re.findall(r'--([\w-]+):\s*([^;]+);', m.group(1))}


def tokens():
    css = STYLES.read_text(encoding='utf-8')
    t = block(css, ':root')
    ten = block(css, 'html.using-controller')
    touch = media(css, '(pointer: coarse)')
    size_of = lambda name: {k.removeprefix('text-'): px(v) for k, v in t.items() if k.startswith('text-')}
    root_scale = re.search(r'html\.using-controller\s*\{[^}]*font-size:\s*([\d.]+)%', css)
    return {
        '$comment': HEADER,
        'version': 1,
        'type': {
            'scale': size_of('text'),
            'pageTitle': clamp(t['page-title']),
            'display': clamp(t['display']),
            'leading': {'tight': float(t['leading-tight']), 'snug': float(t['leading-snug']), 'body': float(t['leading-body'])},
            'tracking': {'display': float(t['tracking-display'].removesuffix('em')), 'heading': float(t['tracking-heading'].removesuffix('em')), 'label': float(t['tracking-label'].removesuffix('em'))},
            'weight': {'body': 400, 'medium': 500, 'strong': 600, 'heading': int(t['weight-heading'])},
        },
        'space': {k.removeprefix('sp-'): px(v) for k, v in t.items() if k.startswith('sp-')},
        'layout': {'gutter': clamp(t['gutter']), 'sectionGap': clamp(t['section-gap']), 'topBar': px(t['topbar-h']), 'sidebar': px(t['sidebar'])},
        'shape': {
            'radiusMultiple': {k.removeprefix('r-'): float(re.search(r'\*\s*([\d.]+)', v).group(1)) if '*' in v else 1 for k, v in t.items() if k in ('r-xs', 'r-sm', 'r-md', 'r-lg', 'r-xl')},
            'pill': px(t['r-full']),
        },
        'depth': {'resting': shadow(t['e-1'])},
        'motion': {
            'duration': {'press': ms(t['dur-1']), 'hoverFocus': ms(t['dur-2']), 'appear': ms(t['dur-3']), 'backdrop': ms(t['dur-4'])},
            'easing': {'out': bezier(t['ease-out']), 'standard': bezier(t['ease-standard'])},
        },
        'control': {
            'height': {'default': px(t['control-h']), 'small': px(t['control-h-sm']), 'large': px(t['control-h-lg'])},
            'heightTouch': {'default': px(touch['control-h']), 'small': px(touch['control-h-sm']), 'large': px(touch['control-h-lg'])},
            'minTarget': 24,
        },
        'card': {'width': px(t['card-w']), 'wideWidth': px(t['card-wide-w']), 'posterRatio': [2, 3], 'wideRatio': [16, 9], 'albumRatio': [1, 1]},
        'focus': {'width': px(t['focus-width']), 'offset': px(t['focus-offset']), 'scale': float(t['focus-scale'])},
        'tenFoot': {
            'textScale': round(float(root_scale.group(1)) / 100, 4),
            'focus': {'width': px(ten['focus-width']), 'offset': px(ten['focus-offset']), 'scale': float(ten['focus-scale'])},
            'cardWidth': px(ten['card-w']),
            'wideCardWidth': px(ten['card-wide-w']),
            'minGutter': px(re.search(r'max\(([^,]+),', ten['gutter']).group(1)),
            'minTarget': 48,
        },
    }


def rgba(value, vars_):
    """A theme colour resolved to (r, g, b, a), a in 0-1. Follows var() and color-mix()."""
    v = value.strip()
    m = re.fullmatch(r'var\(--([\w-]+)\)', v)
    if m:
        return rgba(vars_[m.group(1)], vars_)
    if v.startswith('#'):
        h = v[1:]
        if len(h) == 3:
            h = ''.join(c * 2 for c in h)
        return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 1.0)
    m = re.fullmatch(r'rgba?\(([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)\s*(?:[,/]\s*([\d.]+)\s*)?\)', v)
    if m:
        return (int(m.group(1)), int(m.group(2)), int(m.group(3)), float(m.group(4) or 1))
    m = re.fullmatch(r'rgb\(var\(--([\w-]+)\)\s*/\s*([\d.]+)\)', v)
    if m:
        r, g, b = (int(x) for x in vars_[m.group(1)].split())
        return (r, g, b, float(m.group(2)))
    m = re.fullmatch(r'color-mix\(in srgb,\s*(.+?)\s+([\d.]+)%,\s*(.+)\)', v)
    if m:
        a, p, b = rgba(m.group(1), vars_), float(m.group(2)) / 100, m.group(3)
        if b == 'transparent':
            return (a[0], a[1], a[2], round(a[3] * p, 4))
        c = rgba(b, vars_)
        return tuple(round(a[i] * p + c[i] * (1 - p)) for i in range(3)) + (1.0,)
    raise SystemExit(f'cannot resolve colour: {value}')


def hexa(c):
    r, g, b, a = c
    return f'#{r:02x}{g:02x}{b:02x}' + ('' if a >= 1 else f'{round(a * 255):02x}')


# name in theme.json -> CSS variable
COLORS = {
    'bg': 'bg', 'bg2': 'bg-2', 'bg3': 'bg-3', 'bg4': 'bg-4', 'fg': 'fg', 'fg2': 'fg-2', 'fg3': 'fg-3',
    'accent': 'accent', 'accentHover': 'accent-2', 'accentFg': 'accent-fg', 'accentText': 'accent-text', 'brandAccent': 'brand-accent',
    'danger': 'danger', 'ok': 'ok', 'warn': 'warn', 'border': 'border', 'borderStrong': 'border-strong', 'controlLine': 'control-line',
    'hover': 'hover', 'pressed': 'pressed', 'accentSoft': 'accent-soft', 'accentLine': 'accent-line',
    'okSoft': 'ok-soft', 'warnSoft': 'warn-soft', 'dangerSoft': 'danger-soft', 'focus': 'focus', 'onImage': 'on-image', 'scrim': 'scrim', 'overlay': 'overlay',
}


def theme_colors(css_file, defaults):
    vars_ = dict(defaults)
    vars_.update(block(css_file.read_text(encoding='utf-8'), ':root'))
    return {name: hexa(rgba(vars_[var], vars_)) for name, var in COLORS.items()}, px(vars_['radius'])


def write(path, data, stale):
    text = json.dumps(data, indent=2, ensure_ascii=False) + '\n'
    old = path.read_text(encoding='utf-8').replace('\r\n', '\n') if path.exists() else ''
    if old == text:
        return
    stale.append(str(path))
    if not CHECK:
        path.write_text(text, encoding='utf-8', newline='\n')


def main():
    stale = []
    write(pathlib.Path('themes/tokens.json'), tokens(), stale)
    defaults = block(STYLES.read_text(encoding='utf-8'), ':root')
    for css_file in sorted(pathlib.Path('themes').glob('*/theme.css')):
        meta_file = css_file.parent / 'theme.json'
        meta = json.loads(meta_file.read_text(encoding='utf-8'))
        meta['colors'], meta['radius'] = theme_colors(css_file, defaults)
        write(meta_file, meta, stale)
    if CHECK and stale:
        print('Out of date, run python scripts/design-tokens.py:\n  ' + '\n  '.join(stale))
        sys.exit(1)
    print('design tokens ' + ('up to date' if not stale else f'written: {len(stale)} files'))


main()
