"""Puts the licence header on every source file git tracks, or checks that it's there.

  scripts/license-headers.py                      check this repository (AGPL-3.0-or-later)
  scripts/license-headers.py --fix                add the header where it's missing
  scripts/license-headers.py --repo ../WittyMediaClient --license GPL-3.0-or-later --fix

The header is two comment lines: the SPDX identifier and the copyright line. It goes after
a "#!" line or Swift's "// swift-tools-version" line, which have to stay first. A file is
left alone when it already names a licence (ours or someone else's), when it says it is
generated, and when it lives in a folder of other people's code or of test data.

CI runs the check, so a new file can't arrive without its header.
"""
import argparse
import os
import re
import subprocess
import sys

COPYRIGHT = "Copyright (C) 2026 WittyWilla and contributors"

SLASH = {"go", "ts", "tsx", "js", "jsx", "mjs", "cjs", "swift", "kt", "kts", "c", "h", "cc", "cpp", "hpp", "m", "mm", "java", "rs", "qml"}
HASH = {"sh", "bash", "py", "ps1", "rb"}
BLOCK = {"css"}
# A blank line after the header where the language's tools read the comment that follows as
# belonging to what it precedes (Go's package comments and build constraints).
BLANK_AFTER = {"go", "ps1"}

SKIP_DIRS = ("node_modules/", "vendor/", "third_party/", "testdata/", "dist/", ".tools/")
SKIP_NAMES = re.compile(r"(\.min\.(js|css)$|\.generated\.[a-z]+$|(^|/)gen\.go$|\.pb\.go$|\.d\.ts$)")
GENERATED = re.compile(r"Code generated|DO NOT EDIT|@generated|generated by", re.I)
# Someone else's notice at the top: theirs stays as it is.
FOREIGN = re.compile(r"SPDX-License-Identifier|Copyright \(c\)|Copyright ©|Copyright \d{4}|Licensed under|Permission is hereby granted", re.I)


def header(ext, spdx):
    if ext in SLASH:
        return [f"// SPDX-License-Identifier: {spdx}", f"// {COPYRIGHT}"]
    if ext in HASH:
        return [f"# SPDX-License-Identifier: {spdx}", f"# {COPYRIGHT}"]
    if ext in BLOCK:
        return [f"/* SPDX-License-Identifier: {spdx} */", f"/* {COPYRIGHT} */"]
    return None


def tracked(repo):
    out = subprocess.run(["git", "-C", repo, "ls-files", "-z"], check=True, capture_output=True).stdout
    return [f for f in out.decode().split("\0") if f]


def wanted(path):
    if any(("/" + path).find("/" + d) >= 0 for d in SKIP_DIRS):
        return False
    return not SKIP_NAMES.search(path)


def state(text, spdx):
    """'ok', 'missing', or 'skip' (generated, or under someone else's notice)."""
    top = "\n".join(text.split("\n", 12)[:12])
    if f"SPDX-License-Identifier: {spdx}" in top:
        return "ok"
    if GENERATED.search("\n".join(top.split("\n")[:5])):
        return "skip"
    if FOREIGN.search(top):
        return "skip"
    return "missing"


def add(text, ext, spdx):
    nl = "\r\n" if "\r\n" in text[:2000] else "\n"
    bom = ""
    if text.startswith("﻿"):
        bom, text = "﻿", text[1:]
    lines = text.split(nl)
    keep = 0
    if lines and (lines[0].startswith("#!") or lines[0].startswith("// swift-tools-version")):
        keep = 1
    head = header(ext, spdx)
    if ext in BLANK_AFTER and keep < len(lines) and lines[keep].strip():
        head = head + [""]
    return bom + nl.join(lines[:keep] + head + lines[keep:])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", default=".")
    ap.add_argument("--license", default="AGPL-3.0-or-later", dest="spdx")
    ap.add_argument("--fix", action="store_true")
    ap.add_argument("--exclude", action="append", default=[], help="a path prefix to leave alone (repeatable)")
    a = ap.parse_args()

    missing, fixed = [], 0
    for f in tracked(a.repo):
        ext = f.rsplit(".", 1)[-1].lower() if "." in os.path.basename(f) else ""
        if header(ext, a.spdx) is None or not wanted(f) or any(f.startswith(p) for p in a.exclude):
            continue
        p = os.path.join(a.repo, f)
        if os.path.islink(p) or not os.path.isfile(p):
            continue
        try:
            with open(p, encoding="utf-8", newline="") as fh:
                text = fh.read()
        except UnicodeDecodeError:
            continue
        if state(text, a.spdx) != "missing":
            continue
        if a.fix:
            with open(p, "w", encoding="utf-8", newline="") as fh:
                fh.write(add(text, ext, a.spdx))
            fixed += 1
        else:
            missing.append(f)
    if a.fix:
        print(f"added the {a.spdx} header to {fixed} file(s)")
        return 0
    if missing:
        print(f"{len(missing)} file(s) have no {a.spdx} header (scripts/license-headers.py --fix adds it):", file=sys.stderr)
        for f in missing:
            print("  " + f, file=sys.stderr)
        return 1
    print("every source file has its licence header")
    return 0


if __name__ == "__main__":
    sys.exit(main())
